#[cfg(test)]
mod tests {
    use super::*;
    use aether_ast::FileId;

    #[test]
    fn h_escapes() {
        assert_eq!(h("<a>"), "&lt;a&gt;");
        assert_eq!(h("a & b"), "a &amp; b");
    }

    #[test]
    fn anchor_normalizes() {
        assert_eq!(anchor_for(Path::new("std/iter.ae")), "std-iter-ae");
    }

    #[test]
    fn renders_minimal_site() {
        let mut sm = SourceMap::new();
        let fid = sm.add("x.ae", "## A demo.\nfn one() -> Int effects {} { 1 }\n");
        let m = parse_module(fid, "## A demo.\nfn one() -> Int effects {} { 1 }\n").unwrap();
        let html = render_site("demo", &[(PathBuf::from("x.ae"), m)], Path::new("."));
        assert!(html.contains("<title>demo</title>"));
        assert!(html.contains("one"));
        assert!(html.contains("fn <strong>one</strong>"));
    }

    fn _unused_fid_warning_silencer() -> FileId {
        FileId(0)
    }
}
